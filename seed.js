// ===== ล้างข้อมูลเก่าแล้วใส่ข้อมูลใหม่ =====
db.serialize(() => {
  db.run('DELETE FROM Payment');
  db.run('DELETE FROM Order_Detail');
  db.run('DELETE FROM "Order"');
  db.run('DELETE FROM Menu');
  db.run('DELETE FROM Category');
  db.run('DELETE FROM "Table"');
  db.run('DELETE FROM Employee');
  db.run('DELETE FROM Inventory');
  db.run('DELETE FROM sqlite_sequence');

  categories.forEach((name) => {
    db.run('INSERT INTO Category (Category_Name) VALUES (?)', [name]);
  });

  menus.forEach((m) => {
    db.run(
      'INSERT INTO Menu (Category_ID, Menu_Name, Price, Image_URL, Description, Stock_Quantity, Is_Available) VALUES (?, ?, ?, ?, ?, ?, ?)',
      [m[0], m[1], m[2], null, m[3], m[4], m[5]]
    );
  });

  // ===== ข้อมูลโต๊ะ (Table) 10 โต๊ะ =====
  for (let i = 1; i <= 10; i++) {
    const no = String(i).padStart(2, '0');
    db.run(
      'INSERT INTO "Table" (Table_Number, Table_Name, Table_Status, QR_Code_URL) VALUES (?, ?, ?, ?)',
      [no, 'โต๊ะ ' + no, 'ว่าง', '/table/' + i]
    );
  }

  employees.forEach((e) => {
    db.run('INSERT INTO Employee (Username, Password, Employee_Name, Role) VALUES (?, ?, ?, ?)', e);
  });

  inventory.forEach((v) => {
    db.run('INSERT INTO Inventory (Ingredient_Name, In_Stock_Quantity, Unit, Reorder_Level) VALUES (?, ?, ?, ?)', v);
  });
});

db.close(() => console.log('ใส่ข้อมูลตัวอย่างลง mala.db เรียบร้อย'));
